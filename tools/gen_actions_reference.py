#!/usr/bin/env python3
"""Generate docs/bridge-actions/REFERENCE.md from the catalog snapshot.

    python tools/gen_actions_reference.py                     # resources/actions/catalog.snapshot.json
    python tools/gen_actions_reference.py --catalog x.json --out y.md
    python tools/gen_actions_reference.py --check             # exit 1 if REFERENCE.md is stale

The snapshot is written by the Catch2 test "[actions][snapshot]" (UPDATE_SNAPSHOT=1).
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def schema_summary(schema: dict, indent: int = 0) -> list[str]:
    lines = []
    props = schema.get('properties', {}) or {}
    required = set(schema.get('required', []) or [])
    pad = '  ' * indent
    for name, p in props.items():
        t = p.get('type', '?')
        if t == 'array':
            it = p.get('items', {})
            t = f"array of {it.get('type', '?')}"
        bits = []
        if 'enum' in p:
            bits.append('one of ' + ', '.join(f'`{json.dumps(e)}`' for e in p['enum']))
        if 'minimum' in p or 'maximum' in p:
            bits.append(f"{p.get('minimum', '')}..{p.get('maximum', '')}")
        for k in ('minLength', 'maxLength', 'minItems', 'maxItems'):
            if k in p:
                bits.append(f'{k} {p[k]}')
        if 'default' in p:
            bits.append(f"default `{json.dumps(p['default'])}`")
        if p.get('description'):
            bits.append(p['description'])
        req = ' (required)' if name in required else ''
        lines.append(f"{pad}- `{name}` {t}{req}" + (': ' + '; '.join(bits) if bits else ''))
        if p.get('type') == 'object':
            lines.extend(schema_summary(p, indent + 1))
        elif p.get('type') == 'array' and (p.get('items') or {}).get('type') == 'object':
            lines.extend(schema_summary(p['items'], indent + 1))
    if schema.get('x-exactlyOne'):
        lines.append(f"{pad}- exactly one of: " + ' | '.join('+'.join(g) for g in schema['x-exactlyOne']))
    return lines


def render(catalog: dict) -> str:
    actions = catalog.get('actions', [])
    by_domain: dict[str, list] = OrderedDict()
    for a in sorted(actions, key=lambda a: (a['domain'], a['id'])):
        by_domain.setdefault(a['domain'], []).append(a)
    out = [
        '# Action catalog reference',
        '',
        '<!-- Generated by tools/gen_actions_reference.py from resources/actions/catalog.snapshot.json. Do not edit. -->',
        '',
        f"Catalog version `{catalog.get('catalogVersion', '?')}`, {len(actions)} entries. "
        'Design: [docs/HLSD/bridge-actions.md](../HLSD/bridge-actions.md). Entries with a bridge method are typed methods, '
        'called directly; the rest go through `slicer.invokeAction`.',
        '',
        'Settings inside action params are a list `values: [{key, value}]` with each value a string in the '
        "option's text form (as `slicer.getSettings` reports it), because the params dialect has no free-form maps.",
        '',
        '| Domain | Actions |',
        '|---|---|',
    ]
    for d, acts in by_domain.items():
        out.append(f"| [{d}](#{d}) | " + ', '.join(f"`{a['id']}`" for a in acts) + ' |')
    out.append('')
    for d, acts in by_domain.items():
        out += [f'## {d}', '']
        for a in acts:
            out.append(f"### `{a['id']}` — {a['label']}")
            out.append('')
            out.append(a['summary'])
            out.append('')
            meta = [f"risk **{a['risk']}**", f"confirm {a['confirm']}", f"gate {a['gate']}"]
            if a.get('bridgeMethod'):
                meta.append(f"typed method `{a['bridgeMethod']}`")
            tgt = a.get('target') or {}
            if tgt.get('kind', 'none') != 'none':
                meta.append(f"target {tgt['kind']}" + (' (required)' if tgt.get('required') else ''))
            if a.get('effects'):
                meta.append('effects ' + ', '.join(a['effects']))
            if a.get('longRunning'):
                meta.append('long-running')
            meta.append(f"since {a.get('since', '?')}")
            out.append(' · '.join(meta))
            if a.get('confirmSkipRule'):
                out.append('')
                out.append(f"Confirmation: {a['confirmSkipRule']}.")
            params = schema_summary(a.get('params') or {})
            if params:
                out += ['', 'Params:', ''] + params
            if a.get('examples'):
                out += ['', 'Example: `' + json.dumps(a['examples'][0], separators=(',', ':')) + '`']
            if a.get('ui'):
                out += ['', 'UI: ' + ', '.join(f'`{u}`' for u in a['ui'])]
            out.append('')
    return '\n'.join(out).rstrip() + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--catalog', default=os.path.join(ROOT, 'resources', 'actions', 'catalog.snapshot.json'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'bridge-actions', 'REFERENCE.md'))
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    with open(args.catalog, encoding='utf-8') as fh:
        catalog = json.load(fh)
    text = render(catalog)
    if args.check:
        old = open(args.out, encoding='utf-8').read() if os.path.exists(args.out) else ''
        if old != text:
            print(f'{args.out} is stale; run tools/gen_actions_reference.py')
            return 1
        print('up to date')
        return 0
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print(f"wrote {args.out} ({len(catalog.get('actions', []))} entries)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
