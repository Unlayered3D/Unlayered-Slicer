struct TopCell { double z; int role; bool shell; };
std::map<std::pair<int, int>, TopCell> top_map(const PrintObject &obj, double cell)
{
    BoundingBox bb;
    for (const ExPolygon &ex : obj.layers().front()->lslices) bb.merge(get_extents(ex.contour));
    const Vec2d c = unscale(bb.center());
    std::map<std::pair<int, int>, TopCell> top;
    std::function<void(const ExtrusionEntity *, const Layer *)> visit = [&](const ExtrusionEntity *e, const Layer *layer) {
        if (const auto *cc = dynamic_cast<const ExtrusionEntityCollection *>(e)) { for (auto *x : cc->entities) visit(x, layer); return; }
        std::vector<const ExtrusionPath *> paths;
        if (const auto *p = dynamic_cast<const ExtrusionPath *>(e)) paths.push_back(p);
        else if (const auto *mp = dynamic_cast<const ExtrusionMultiPath *>(e)) for (const ExtrusionPath &p : mp->paths) paths.push_back(&p);
        else if (const auto *lp = dynamic_cast<const ExtrusionLoop *>(e)) for (const ExtrusionPath &p : lp->paths) paths.push_back(&p);
        for (const ExtrusionPath *p : paths) {
            const Points3 &pts = p->polyline.points;
            for (size_t i = 0; i + 1 < pts.size(); ++ i) {
                const Vec3d a(unscale<double>(pts[i].x()), unscale<double>(pts[i].y()), unscale<double>(pts[i].z()));
                const Vec3d b(unscale<double>(pts[i + 1].x()), unscale<double>(pts[i + 1].y()), unscale<double>(pts[i + 1].z()));
                const int ns = std::max(1, int(std::ceil((b - a).head<2>().norm() / 0.1)));
                for (int k = 0; k <= ns; ++ k) {
                    const Vec3d q = a + (b - a) * (double(k) / ns);
                    const std::pair<int, int> key(int(std::floor((q.x() - c.x()) / cell)), int(std::floor((q.y() - c.y()) / cell)));
                    const double z = layer->print_z + q.z();
                    auto it = top.find(key);
                    if (it == top.end() || it->second.z < z - 1e-6)
                        top[key] = { z, int(p->role()), p->nonplanar_shell };
                }
            }
        }
    };
    for (const Layer *layer : obj.layers())
        for (const LayerRegion *lr : layer->regions()) { visit(&lr->fills, layer); visit(&lr->perimeters, layer); }
    return top;
}

// Area (mm2) away from the curved shell whose visible top differs from the planar slice: planar material
// was removed (or changed) where no curved top covers it.
double touched_outside_shell(const PrintObject &on, const PrintObject &off)
{
    const double cell = 0.5;
    const auto t_on = top_map(on, cell), t_off = top_map(off, cell);
    std::set<std::pair<int, int>> near_shell;
    for (const auto &[k, v] : t_on)
        if (v.shell)
            for (int dj = -2; dj <= 2; ++ dj)
                for (int di = -2; di <= 2; ++ di) near_shell.insert({ k.first + di, k.second + dj });
    double bad = 0.;
    for (const auto &[k, v] : t_off) {
        if (near_shell.count(k))
            continue;
        auto it = t_on.find(k);
        if (it == t_on.end() || std::abs(it->second.z - v.z) > 1e-3 || it->second.role != v.role)
            bad += cell * cell;
    }
    return bad;
}
