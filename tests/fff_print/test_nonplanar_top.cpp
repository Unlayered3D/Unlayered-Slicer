// The extrusion moves of a G-code up to (not including) the first layer whose Z tag is above z_stop.
std::vector<std::string> extrusions_below(const std::string &gcode, double z_stop)
{
    std::vector<std::string> out;
    std::istringstream in(gcode);
    std::string        line;
    const std::regex   ztag(R"(^;Z:(-?\d*\.?\d+))");
    std::smatch        m;
    while (std::getline(in, line)) {
        if (std::regex_search(line, m, ztag) && std::stod(m[1].str()) > z_stop + 1e-6)
            break;
        if (line.rfind("G1", 0) != 0) continue;
        std::string code = line.substr(0, line.find(';'));
        while (! code.empty() && code.back() == ' ') code.pop_back();
        if (code.find('E') != std::string::npos && (code.find('X') != std::string::npos || code.find('Y') != std::string::npos))
            out.push_back(code);
    }
    return out;
}

// E by layer (Z tag) and ;TYPE: role, up to z_stop.
std::map<long, std::map<std::string, double>> role_e_by_layer(const std::string &gcode, double z_stop)
{
    std::map<long, std::map<std::string, double>> out;
    std::istringstream in(gcode);
    std::string        line, role = "?";
    long               z = -1;
    const std::regex   e_re(R"(E(-?\d*\.?\d+))");
    std::smatch        m;
    while (std::getline(in, line)) {
        if (line.rfind(";Z:", 0) == 0) {
            const double zz = std::stod(line.substr(3));
            if (zz > z_stop + 1e-6) break;
            z = std::lround(zz * 1000.);
        } else if (line.rfind(";TYPE:", 0) == 0)
            role = line.substr(6);
        else if (line.rfind("G1", 0) == 0 && z >= 0) {
            const std::string code = line.substr(0, line.find(';'));
            if ((code.find('X') != std::string::npos || code.find('Y') != std::string::npos) && std::regex_search(code, m, e_re) && std::stod(m[1].str()) > 0.)
                out[z][role] += std::stod(m[1].str());
        }
    }
    return out;
}

size_t count_open_walls(const ExtrusionEntity *e)
{
    if (const auto *c = dynamic_cast<const ExtrusionEntityCollection *>(e)) {
        size_t n = 0;
        for (const ExtrusionEntity *x : c->entities) n += count_open_walls(x);
        return n;
    }
    if (dynamic_cast<const ExtrusionLoop *>(e)) return 0;
    std::vector<const ExtrusionPath *> paths;
    if (const auto *p = dynamic_cast<const ExtrusionPath *>(e)) paths.push_back(p);
    else if (const auto *mp = dynamic_cast<const ExtrusionMultiPath *>(e)) for (const ExtrusionPath &p : mp->paths) paths.push_back(&p);
    size_t n = 0;
    for (const ExtrusionPath *p : paths)
        if (! p->nonplanar_shell && (p->role() == erPerimeter || p->role() == erExternalPerimeter)) ++ n;
    return n;
}

size_t count_loops(const ExtrusionEntity *e)
{
    if (const auto *c = dynamic_cast<const ExtrusionEntityCollection *>(e)) {
        size_t n = 0;
        for (const ExtrusionEntity *x : c->entities) n += count_loops(x);
        return n;
    }
    return dynamic_cast<const ExtrusionLoop *>(e) ? 1 : 0;
}

